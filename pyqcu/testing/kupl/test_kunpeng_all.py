def write_identity_gauge(path: Path, lattice: Sequence[int],
                         dtype: str) -> Optional[Path]:
    try:
        import numpy as np
        import h5py
    except Exception as exc:  # noqa: BLE001
        eprint(f"[SKIP] cannot write identity gauge: {exc}")
        return None
    np_dtype = np.dtype(np.complex64 if dtype == "c64" else np.complex128)
    data = np.zeros((3, 3, 4, *lattice), dtype=np_dtype)
    eye = np.eye(3, dtype=np_dtype)
    for direction in range(4):
        data[:, :, direction] = eye[:, :, None, None, None, None]
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    with h5py.File(tmp, "w") as handle:
        handle.create_dataset("data", data=data)
        handle.attrs["format"] = "pyqcu.simple.v1"
        handle.attrs["layout"] = "[color,color,direction,x,y,z,t]"
        handle.attrs["generator"] = "identity gauge"
    os.replace(tmp, path)
