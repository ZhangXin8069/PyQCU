PROFILE_RE = re.compile(
    r"PYQCU::KUPL::OPT_PROFILE:rank=(\d+) rank_of=(\d+)\s*\n"
    r"dslash=([0-9.eE+-]+)/(\d+) bytes=([0-9.eE+-]+)MB "
    r"gbps_rank=([0-9.eE+-]+) gbps_total=([0-9.eE+-]+)\s*\n"
    r"clover=([0-9.eE+-]+)/(\d+) bytes=([0-9.eE+-]+)MB "
    r"gbps_rank=([0-9.eE+-]+) gbps_total=([0-9.eE+-]+)\s*\n"
    r"reduce=([0-9.eE+-]+)/(\d+)\s*\n"
    r"halo_pack=([0-9.eE+-]+) halo_sync=([0-9.eE+-]+) "
    r"halo_copy=([0-9.eE+-]+)\s*\n"
    r"phases prepare=([0-9.eE+-]+) solve=([0-9.eE+-]+) "
    r"reconstruct=([0-9.eE+-]+)",
    re.S,
)


def parse_profile(text: str) -> Dict[str, Any]:
    matches = list(PROFILE_RE.finditer(text))
    if not matches:
        return {}
    selected = next((m for m in matches if m.group(1) == "0"), matches[0])
    values = selected.groups()
    keys = [
        "profile_rank", "profile_ranks",
        "dslash_seconds", "dslash_calls", "dslash_bytes_mb",
        "dslash_gbps_rank", "dslash_gbps_total",
        "clover_seconds", "clover_calls", "clover_bytes_mb",
        "clover_gbps_rank", "clover_gbps_total",
        "reduce_seconds", "reduce_calls",
        "halo_pack_seconds", "halo_sync_seconds", "halo_copy_seconds",
        "phase_prepare_seconds", "phase_solve_seconds",
        "phase_reconstruct_seconds",
    ]
    result: Dict[str, Any] = {}
    for key, value in zip(keys, values):
        if key in ("profile_rank", "profile_ranks", "dslash_calls",
                   "clover_calls", "reduce_calls"):
            result[key] = int(value)
        else:
            result[key] = float(value)
    return result


