def prewarm_run_id(role: str, lattice: Sequence[int], dtype: str,
                   kind: str, seed: int) -> str:
    payload = json.dumps({"role": role, "lattice": list(lattice), "dtype": dtype,
                          "kind": kind, "seed": int(seed)},
                         sort_keys=True, separators=(",", ":"))
    return "prewarm-" + hashlib.sha1(payload.encode("utf-8")).hexdigest()[:16]


def prewarm_row(role: str, info: Dict[str, Any], lattice: Sequence[int],
                dtype: str, kind: str, seed: int,
                hashes: HashCache) -> Dict[str, Any]:
    """One CSV row describing an input generation/prewarm pass."""
    path = info["path"]
    row: Dict[str, Any] = {
        "run_id": prewarm_run_id(role, lattice, dtype, kind, seed),
        "phase": "prewarm",
        "solver": "input_prewarm",
        "dtype": dtype,
        "lattice": list(lattice),
        "lat_x": lattice[0], "lat_y": lattice[1],
        "lat_z": lattice[2], "lat_t": lattice[3],
        "seed": int(seed),
        "status": "PASS" if path is not None else "FAIL",
        "notes": list(info["notes"]),
    }
    if role == "source":
        row["source_kind"] = kind
        row["source_path"] = str(path) if path else None
        row["source_sha256"] = hashes.sha256(path)
        row["source_generate_seconds"] = info["generate_seconds"]
        row["source_prewarm_seconds"] = info["prewarm_seconds"]
        row["source_read_mode"] = info["read_mode"]
    else:
        row["gauge_kind"] = kind
        row["gauge_path"] = str(path) if path else None
        row["gauge_sha256"] = hashes.sha256(path)
        row["gauge_generate_seconds"] = info["generate_seconds"]
        row["gauge_prewarm_seconds"] = info["prewarm_seconds"]
        row["gauge_read_mode"] = info["read_mode"]
    row["notes"].append(f"{role}_origin={info['origin']}")
    if info.get("prewarm_bytes"):
        row["notes"].append(f"prewarm_bytes={int(info['prewarm_bytes'])}")
    return row


def mode_prewarm(args: argparse.Namespace) -> int:
    """Pre-generate and page-cache-warm every input the matrix will read.

    Solving L24/L32 rows is dominated by *input* cost on a cold page cache
    (a 255 MB gauge read by 16 ranks without MPI-IO), so the artifacts are
    produced and warmed once here and then re-read as ``pre-generated`` rows.
    """
    outdir = Path(args.outdir).expanduser()
    outdir.mkdir(parents=True, exist_ok=True)
    hashes = HashCache(outdir / "file_hashes.json")
    lattice = as_int4(args.lat)
    dtype = args.dtype
    sources = [item for item in args.sources.split(",") if item]
    gauges = [item for item in args.gauge_kinds.split(",") if item]
    seeds = [int(item) for item in args.seeds.split(",") if item]
    csv_file = (Path(args.csv).expanduser() if args.csv
                else csv_path(outdir, "kupl_kunpeng_inputs.csv"))
    rows: List[Dict[str, Any]] = []
    seen: Dict[str, Dict[str, Any]] = {}
    for seed in seeds:
        for kind in sources:
            info = resolve_source(outdir, lattice, kind, seed, dtype, prewarm=True)
            if info["path"] is not None and str(info["path"]) in seen:
                seen[str(info["path"])]["notes"].append(
                    f"alias source_kind={kind} seed={seed}")
                continue
            row = prewarm_row("source", info, lattice, dtype, kind, seed, hashes)
            rows.append(row)
            if info["path"] is not None:
                seen[str(info["path"])] = row
        for kind in gauges:
            info = resolve_gauge(outdir, lattice, kind, seed, dtype, prewarm=True)
            if info["path"] is not None and str(info["path"]) in seen:
                seen[str(info["path"])]["notes"].append(
                    f"alias gauge_kind={kind} seed={seed}")
                continue
            row = prewarm_row("gauge", info, lattice, dtype, kind, seed, hashes)
            rows.append(row)
            if info["path"] is not None:
                seen[str(info["path"])] = row
    for row in rows:
        write_row(outdir, row, csv_file)
        print(json.dumps({key: row.get(key) for key in
                          ("run_id", "source_kind", "gauge_kind", "source_path",
                           "gauge_path", "source_generate_seconds",
                           "gauge_generate_seconds", "source_prewarm_seconds",
                           "gauge_prewarm_seconds", "source_read_mode",
                           "gauge_read_mode", "status")},
                         ensure_ascii=False))
    failed = [row["run_id"] for row in rows if row.get("status") != "PASS"]
    print(json.dumps({"inputs": len(rows), "failed": failed,
                      "csv": str(csv_file),
                      "status": "PASS" if not failed else "FAIL"},
                     ensure_ascii=False))
    return 0 if not failed else 1


