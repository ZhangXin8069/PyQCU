def write_point_source(path: Path, lattice: Sequence[int],
                       dtype: str) -> Optional[Path]:
    try:
        import numpy as np
        import h5py
    except Exception as exc:  # noqa: BLE001
        eprint(f"[SKIP] cannot write point source: {exc}")
        return None
    np_dtype = np.dtype(np.complex64 if dtype == "c64" else np.complex128)
    data = np.zeros((4, 3, *lattice), dtype=np_dtype)
    data[:, :, 0, 0, 0, 0] = 1.0
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    with h5py.File(tmp, "w") as handle:
        handle.create_dataset("data", data=data)
        handle.attrs["format"] = "pyqcu.simple.v1"
        handle.attrs["layout"] = "[spin,color,x,y,z,t]"
        handle.attrs["generator"] = "point source at [0,0,0,0], all spin/color"
    os.replace(tmp, path)
    return path


