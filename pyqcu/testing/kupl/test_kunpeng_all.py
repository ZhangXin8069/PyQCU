def base_row(args: argparse.Namespace, lattice: Sequence[int], dtype: str,
             solver: str, restart: int, grid: Sequence[int],
             ranks: int, threads: int, shm: int, source: str,
             gauge: str, seed: int) -> Dict[str, Any]:
    levels = 2 if solver == "mg2" else 1
    mg_restart = int(restart) if solver in ("mg1", "mg2") else 0
    if solver == "bistabcg":
        mg_restart = 0
    grid_mode = "t-finest" if tuple(grid) == (1, 1, 1, ranks) else "balanced"
    return {
        "phase": "solve",
        "solver": solver,
        "dtype": dtype,
        "atol": float(args.atol) if args.atol is not None else auto_atol(dtype),
        "lattice": list(lattice),
        "lat_x": lattice[0], "lat_y": lattice[1],
        "lat_z": lattice[2], "lat_t": lattice[3],
        "mass": float(args.mass),
        "csw": float(args.csw),
        "kappa": 1.0 / (2.0 * float(args.mass) + 8.0),
        "ranks": int(ranks), "threads": int(threads),
        "rank_x_thread": f"{int(ranks)}x{int(threads)}",
        "grid": list(grid), "grid_mode": grid_mode,
        "shm": int(shm),
        "source_kind": source,
        "seed": int(seed),
        "gauge_kind": gauge,
        "mg_levels": int(levels),
        "mg_restart": int(mg_restart),
        "mg_grid": list(args.mg_grid),
        "mg_dof": list(args.dof[:levels]),
        "nv_iters": int(args.nv_iters),
        "coarse_max_iter": int(args.coarse_max_iter),
        "coarse_tol_factor": float(args.coarse_tol_factor),
        "deflate": not bool(args.no_deflate),
        "max_iter": int(args.max_iter),
        "notes": [],
    }


def row_id(row: Dict[str, Any]) -> str:
    keys = ("solver", "dtype", "atol", "lattice", "ranks", "threads",
            "grid", "shm", "source_kind", "seed", "gauge_kind",
            "mg_levels", "mg_restart", "mg_grid", "mg_dof", "nv_iters",
            "coarse_max_iter", "coarse_tol_factor", "deflate")
    payload = {key: row.get(key) for key in keys}
    text = json.dumps(payload, sort_keys=True, separators=(",", ":"))
    return hashlib.sha1(text.encode("utf-8")).hexdigest()[:16]


def attach_run_id(row: Dict[str, Any], args: argparse.Namespace) -> str:
    """Assign ``run_id``; ``--run-label`` keeps variants of one config apart.

    ``run_id`` is derived from the *configuration* only, so a cold and a warm
    measurement of the same case would otherwise share one ``rows/*.json``.
    """
    base = row_id(row)
    label = str(getattr(args, "run_label", "") or "").strip()
    row["run_id"] = f"{base}-{label}" if label else base
    return row["run_id"]


def expand_rows(args: argparse.Namespace) -> List[Dict[str, Any]]:
    lattices = [LATTICES[name] for name in args.lattices.split(",") if name]
    dtypes = [item for item in args.dtypes.split(",") if item]
    solvers = [item for item in args.solvers.split(",") if item]
    grid_modes = [item for item in args.grid_modes.split(",") if item]
    ranks_list = [int(item) for item in args.ranks_list.split(",") if item]
    threads_list = [int(item) for item in args.threads_list.split(",") if item]
    shm_list = [int(item) for item in args.shm_list.split(",") if item]
    sources = [item for item in args.sources.split(",") if item]
    gauges = [item for item in args.gauge_kinds.split(",") if item]
    seeds = [int(item) for item in args.seeds.split(",") if item]
    restarts = [int(item) for item in args.mg_restarts.split(",") if item]
    max_total = int(args.max_total_threads)
    rows: List[Dict[str, Any]] = []
    for lattice in lattices:
        for ranks in ranks_list:
            for mode in grid_modes:
                try:
                    grid = choose_grid(lattice, ranks, mode)
                except ValueError:
                    continue
                for threads in threads_list:
                    if not valid_rank_thread(ranks, threads, max_total):
                        continue
                    for dtype in dtypes:
                        for solver in solvers:
                            if solver == "mg2":
                                candidate_restarts = restarts
                            elif solver == "mg1":
                                candidate_restarts = [0]
                            else:
                                candidate_restarts = [0]
                            for restart in candidate_restarts:
                                for shm in shm_list:
                                    for source in sources:
                                        for gauge in gauges:
                                            for seed in seeds:
                                                row = base_row(
                                                    args, lattice, dtype, solver,
                                                    restart, grid, ranks, threads,
                                                    shm, source, gauge, seed)
                                                attach_run_id(row, args)
                                                rows.append(row)
    # Stable order and de-duplication.
    seen = set()
    unique = []
    for row in rows:
        if row["run_id"] in seen:
            continue
        seen.add(row["run_id"])
        unique.append(row)
    return unique


def single_row(args: argparse.Namespace) -> Dict[str, Any]:
    lattice = as_int4(args.lat)
    ranks = int(args.ranks)
    threads = int(args.threads)
    if args.grid is not None:
        grid = as_int4(args.grid)
    else:
        grid = choose_grid(lattice, ranks, args.grid_mode)
    solver = args.solver
    restart = 0 if solver == "bistabcg" else int(args.mg_restart)
    row = base_row(args, lattice, args.dtype, solver, restart, grid, ranks,
                   threads, args.shm, args.source, args.gauge, args.seed)
    attach_run_id(row, args)
    return row


