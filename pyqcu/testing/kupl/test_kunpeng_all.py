def resolve_source(outdir: Path, lattice: Sequence[int], kind: str, seed: int,
                   dtype: str, prewarm: bool = False) -> Dict[str, Any]:
    """Resolve, generate (if needed) and optionally prewarm the source file.

    Reuse order: readable production file -> readable file from ``outdir`` ->
    generate into ``outdir``.  A production file that today's ``h5py`` cannot
    open is skipped (with a note) instead of failing the solve.
    """
    notes: List[str] = []
    candidates: List[Tuple[str, Path]] = []
    if kind != "random" or int(seed) == 42:
        production = production_source_path(lattice, kind, seed)
        if production is not None:
            candidates.append(("production", production))
    fallback = source_fallback_path(outdir, lattice, kind, seed, dtype)
    candidates.append(("outdir", fallback))
    path: Optional[Path] = None
    origin: Optional[str] = None
    for name, candidate in candidates:
        if not candidate.is_file():
            continue
        ok, reason = h5_readable(candidate)
        if not ok:
            notes.append(f"{name} source unreadable ({reason}): {candidate}")
            continue
        path, origin = candidate, name
        break
    generated_seconds: Optional[float] = None
    if path is None:
        fallback.parent.mkdir(parents=True, exist_ok=True)
        started = time.perf_counter()
        if kind == "point":
            path = write_point_source(fallback, lattice, dtype)
        elif kind == "random":
            path = generate_random_source(fallback, lattice, seed, dtype)
        elif kind in ("ones", "real1"):
            path = write_wall_source(fallback, lattice, dtype)
        else:
            notes.append(f"unsupported source kind {kind!r}")
            return artifact_result("source", None, None, None, None, notes)
        generated_seconds = time.perf_counter() - started
        origin = "generated"
        if path is None:
            notes.append("source generation failed")
            return artifact_result("source", None, None, generated_seconds, None, notes)
        ok, reason = h5_readable(path)
        if not ok:
            notes.append(f"generated source unreadable ({reason}): {path}")
    prewarm_result = prewarm_h5(path) if prewarm and path is not None else None
    if prewarm_result is not None and prewarm_result.get("status") != "PASS":
        notes.append(f"source prewarm failed: {prewarm_result.get('error')}")
    return artifact_result("source", path, origin, generated_seconds,
                           prewarm_result, notes)


