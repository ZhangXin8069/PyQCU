def solve_row(args: argparse.Namespace, row: Dict[str, Any], outdir: Path,
              index: Dict[str, Any], hashes: HashCache) -> Dict[str, Any]:
    row_started = time.perf_counter()
    out = dict(row)
    out["phase"] = "solve"
    out["run_id"] = row.get("run_id") or row_id(row)
    notes = list(out.get("notes") or [])
    # artifacts: resolve -> (generate) -> (prewarm), each step timed
    prewarm_inputs = bool(getattr(args, "prewarm_inputs", False))
    gauge_info = resolve_gauge(outdir, row["lattice"], row["gauge_kind"],
                               row["seed"], row["dtype"],
                               prewarm=prewarm_inputs)
    source_info = resolve_source(outdir, row["lattice"], row["source_kind"],
                                 row["seed"], row["dtype"],
                                 prewarm=prewarm_inputs)
    gauge = gauge_info["path"]
    source = source_info["path"]
    out["gauge_path"] = str(gauge) if gauge else None
    out["source_path"] = str(source) if source else None
    out["gauge_file_dtype"] = "c64" if gauge and "c64" in gauge.name else (
        "c128" if gauge else None)
    out["source_file_dtype"] = "c64" if source and "c64" in source.name else (
        "c128" if source else None)
    out["gauge_sha256"] = hashes.sha256(gauge)
    out["source_sha256"] = hashes.sha256(source)
    out["gauge_generate_seconds"] = gauge_info["generate_seconds"]
    out["source_generate_seconds"] = source_info["generate_seconds"]
    out["gauge_prewarm_seconds"] = gauge_info["prewarm_seconds"]
    out["source_prewarm_seconds"] = source_info["prewarm_seconds"]
    out["gauge_read_mode"] = gauge_info["read_mode"]
    out["source_read_mode"] = source_info["read_mode"]
    notes.extend(source_info["notes"])
    notes.extend(gauge_info["notes"])
    notes.append(f"source_origin={source_info['origin']}")
    notes.append(f"gauge_origin={gauge_info['origin']}")
    if gauge is None:
        notes.append("gauge missing")
    if source is None:
        notes.append("source missing")
    allow_missing = bool(getattr(args, "allow_missing_inputs", False))
    cache = None
    if row["solver"] == "mg2":
        kind = row.get("cache_kind") or (
            "global" if row.get("grid_mode") == "t-finest" else "ranked")
        key = cache_key(row, kind)
        cache = index.get(key)
        if cache is None and kind == "ranked":
            global_key = cache_key(row, "global")
            global_cache = index.get(global_key)
            if global_cache is not None:
                cache = global_cache
                kind = "global"
                notes.append("ranked cache unavailable; using global cache")
        if cache is None:
            out.update({"status": "SKIP", "notes": notes + [f"cache missing: {kind}"],
                        "timeout": False, "review": False, "error": None,
                        "elapsed_seconds": time.perf_counter() - row_started})
            return out
        out["cache_kind"] = kind
        out["cache_path"] = cache.get("path")
        out["cache_sha256"] = hashes.sha256(Path(cache["path"])) if cache.get("path") else None
        out["build_mg_cache_seconds"] = cache.get("build_mg_cache_seconds")
        identity = cache.get("identity") or {}
        if identity.get("dof"):
            out["mg_dof"] = list(identity["dof"])
        if identity.get("mg_grid"):
            out["mg_grid"] = list(identity["mg_grid"])
        if identity.get("nv_iters"):
            out["nv_iters"] = int(identity["nv_iters"])
        identity_text = json.dumps(identity, sort_keys=True, separators=(",", ":"))
        out["cache_identity_sha256"] = hashlib.sha256(identity_text.encode()).hexdigest()[:16]
    if (gauge is None or source is None) and not allow_missing:
        out.update({"status": "SKIP", "timeout": False, "review": False,
                    "error": None, "elapsed_seconds": time.perf_counter() - row_started})
        return out
    report = outdir / "reports" / f"{out['run_id']}.json"
    solution = None if args.no_solution else outdir / "solutions" / f"{out['run_id']}.h5"
    command = driver_command(out, cache, args, outdir, report, solution)
    env = base_env(row["threads"], row["shm"], row["dtype"])
    out_log = outdir / "logs" / f"{out['run_id']}.out"
    err_log = outdir / "logs" / f"{out['run_id']}.err"
    result = run_command(command, env, REPO, out_log, err_log,
                         args.hard_timeout, args.timeout)
    mpirun_seconds = result.get("elapsed_seconds")
    out.update(result)
    out["elapsed_seconds"] = time.perf_counter() - row_started
    out["out_path"] = str(out_log)
    out["err_path"] = str(err_log)
    out["report_path"] = str(report) if report.is_file() else None
    out["report_sha256"] = hashes.sha256(report) if report.is_file() else None
    out["solution_path"] = str(solution) if solution and solution.is_file() else None
    out["solution_sha256"] = hashes.sha256(solution) if solution and solution.is_file() else None
    data = read_json(report, {}) or {}
    for key in ("wall_seconds", "builder_seconds", "iterations",
                "final_true_residual", "residual_source", "converged",
                "verify_status", "input_prebind_seconds", "gauge_read_seconds",
                "source_read_seconds", "hdf5_mpio_read", "residual_seconds",
                "status", "atol", "levels", "restart", "coarse_source"):
        if key in data:
            out[key] = data.get(key)
    residual = data.get("final_true_residual")
    source_text = str(data.get("residual_source") or "")
    out["relative_full_residual"] = residual if "distributed" not in source_text else None
    out["distributed_relative_residual"] = residual if "distributed" in source_text else None
    text = read_text(out_log) + "\n" + read_text(err_log)
    out.update(parse_profile(text))
    if "shared halo handshake timeout" in text:
        notes.append("shared halo handshake timeout (MG+shm asymmetric)")
    out.update(node_frequency())
    if not h5py_has_mpi():
        notes.append("h5py lacks MPI; HDF5 parallel read disabled")
    if result["timeout"]:
        out["status"] = "TIMEOUT"
        notes.append(f"hard timeout after {args.hard_timeout}s")
    elif not report.is_file():
        out["status"] = "FAIL"
        notes.append("no report.json")
    if result["review"]:
        notes.append(f"review threshold {args.timeout}s exceeded")
    if (out.get("status") == "PASS" and cache is not None
            and data.get("builder_seconds") is not None):
        notes.append("builder_seconds is cache load/build time")
    if mpirun_seconds is not None:
        notes.append(f"mpirun_seconds={float(mpirun_seconds):.3f} "
                     f"(elapsed_seconds includes startup/generate/prewarm)")
    out["elapsed_seconds"] = time.perf_counter() - row_started
    out["notes"] = notes
    return out


