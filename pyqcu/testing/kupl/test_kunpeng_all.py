def generate_random_gauge(path: Path, lattice: Sequence[int], seed: int,
                          dtype: str) -> Optional[Path]:
    """Deterministic random SU(3) gauge, saved in PyQCU [3,3,4,x,y,z,t].

    Pure NumPy QR construction: no torch/mpi4py import in this process.
    Suitable for the small validation lattice; large lattices should use the
    production gauge or a compiled generator.
    """
    try:
        import numpy as np
        import h5py
    except Exception as exc:  # noqa: BLE001
        eprint(f"[SKIP] cannot generate random gauge: {exc}")
        return None
    np_dtype = np.dtype(np.complex64 if dtype == "c64" else np.complex128)
    rng = np.random.default_rng(int(seed))
    data = np.empty((3, 3, 4, *lattice), dtype=np_dtype)
    for direction in range(4):
        raw = (rng.normal(size=(*lattice, 3, 3)) +
               1j * rng.normal(size=(*lattice, 3, 3)))
        q, r = np.linalg.qr(raw)
        diagonal = np.diagonal(r, axis1=-2, axis2=-1)
        phase = diagonal / np.maximum(np.abs(diagonal), 1e-300)
        q = q * phase[..., None, :]
        det = np.linalg.det(q)
        q = q * np.exp(-1j * np.angle(det) / 3.0)[..., None, None]
        data[:, :, direction] = np.moveaxis(q, (-2, -1), (0, 1)).astype(np_dtype)
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    with h5py.File(tmp, "w") as handle:
        handle.create_dataset("data", data=data)
        handle.attrs["format"] = "pyqcu.simple.v1"
        handle.attrs["layout"] = "[color,color,direction,x,y,z,t]"
        handle.attrs["generator"] = "NumPy QR random SU(3), seed"
        handle.attrs["seed"] = int(seed)
    os.replace(tmp, path)
    return path


