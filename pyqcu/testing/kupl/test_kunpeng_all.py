def mode_solve(args: argparse.Namespace) -> int:
    outdir = Path(args.outdir).expanduser()
    outdir.mkdir(parents=True, exist_ok=True)
    hashes = HashCache(outdir / "file_hashes.json")
    index = load_cache_index(outdir)
    rows = expand_rows(args) if args.expand else [single_row(args)]
    rows = select_shard(rows, args)
    csv_file = Path(args.csv).expanduser() if args.csv else csv_path(outdir)
    done = 0
    for row in rows:
        if args.resume:
            existing = read_json(outdir / "rows" / f"{row['run_id']}.json", None)
            if isinstance(existing, dict) and (
                    existing.get("status") in ("PASS", "SKIP")
                    or (args.skip_failed and existing.get("status") == "FAIL")):
                done += 1
                continue
        result = solve_row(args, row, outdir, index, hashes)
        write_row(outdir, result, csv_file)
        done += 1
        print(json.dumps({key: result.get(key) for key in
                          ("run_id", "solver", "dtype", "rank_x_thread",
                           "grid", "shm", "source_kind", "source_read_mode",
                           "gauge_read_mode", "mg_restart", "status",
                           "wall_seconds", "elapsed_seconds",
                           "source_read_seconds", "gauge_read_seconds",
                           "source_generate_seconds", "gauge_generate_seconds",
                           "final_true_residual", "dslash_gbps_rank")},
                         ensure_ascii=False))
    print(json.dumps({"done": done, "csv": str(csv_file), "status": "PASS"},
                     ensure_ascii=False))
    return 0


def mode_run(args: argparse.Namespace) -> int:
    outdir = Path(args.outdir).expanduser()
    outdir.mkdir(parents=True, exist_ok=True)
    hashes = HashCache(outdir / "file_hashes.json")
    index = load_cache_index(outdir)
    row = single_row(args)
    result = solve_row(args, row, outdir, index, hashes)
    csv_file = Path(args.csv).expanduser() if args.csv else csv_path(outdir)
    write_row(outdir, result, csv_file)
    print(json.dumps(result, ensure_ascii=False, indent=2, default=str))
    return 0


def mode_merge(args: argparse.Namespace) -> int:
    outdir = Path(args.outdir).expanduser()
    csv_file = Path(args.csv).expanduser() if args.csv else csv_path(outdir)
    return merge_rows(outdir, csv_file)


def mode_validate(args: argparse.Namespace) -> int:
    """Small 2-rank c64 BiCGStab + 2-level MG smoke test."""
    outdir = Path(args.outdir).expanduser() / "validate"
    outdir.mkdir(parents=True, exist_ok=True)
    hashes = HashCache(outdir / "file_hashes.json")
    args.lat = (8, 8, 8, 16)
    args.grid = (2, 1, 1, 1)
    args.ranks = 2
    args.threads = 2
    args.dtype = "c64"
    args.atol = 1e-5
    args.max_iter = 300
    args.mass = -0.277
    args.csw = 1.160920226
    args.source = "ones"
    args.gauge = "random"
    args.seed = 42
    args.timeout = 120
    args.hard_timeout = 180
    args.mg_grid = (2, 2, 2, 2)
    args.dof = (12, 2, 2, 2, 2)
    args.nv_iters = 1
    args.coarse_max_iter = 200
    args.coarse_tol_factor = 1e4
    args.solver = "bistabcg"
    args.mg_restart = 0
    args.shm = 0
    args.no_solution = True
    args.allow_missing_inputs = True
    args.prewarm_inputs = True
    rows: List[Dict[str, Any]] = []
    # BiCGStab on the small lattice with identity gauge / random source.
    bicg = single_row(args)
    bicg["run_id"] = row_id(bicg)
    result = solve_row(args, bicg, outdir, {}, hashes)
    rows.append(result)
    print(json.dumps({"check": "bistabcg", "status": result.get("status"),
                      "residual": result.get("final_true_residual"),
                      "it": result.get("iterations"),
                      "source_read_mode": result.get("source_read_mode"),
                      "gauge_read_mode": result.get("gauge_read_mode"),
                      "source_generate_seconds": result.get("source_generate_seconds"),
                      "source_prewarm_seconds": result.get("source_prewarm_seconds"),
                      "source_read_seconds": result.get("source_read_seconds"),
                      "gauge_generate_seconds": result.get("gauge_generate_seconds"),
                      "gauge_prewarm_seconds": result.get("gauge_prewarm_seconds"),
                      "gauge_read_seconds": result.get("gauge_read_seconds"),
                      "elapsed_seconds": result.get("elapsed_seconds"),
                      "wall_seconds": result.get("wall_seconds")},
                     ensure_ascii=False))
    # Build a 1-rank global cache (identity preserved by a separate driver
    # report path), then MG level=2 with 2 ranks.
    args.solver = "mg2"
    args.mg_restart = 5
    mg = single_row(args)
    mg["cache_kind"] = "global"
    mg["run_id"] = row_id(mg)
    cache = outdir / "caches" / "validate_small_global.h5"
    manifest = outdir / "caches" / "validate_small_global.json"
    cache.parent.mkdir(parents=True, exist_ok=True)
    build_args = argparse.Namespace(**vars(args))
    build_args.threads = 2
    build_args.hard_timeout = 180
    build_args.timeout = 120
    built = build_global_cache(build_args, mg, cache, manifest, outdir, hashes)
    print(json.dumps({"check": "mg_cache", "status": built.get("status"),
                      "seconds": built.get("build_mg_cache_seconds")},
                     ensure_ascii=False))
    mg_ok = bool(built.get("path")) and built.get("identity") is not None
    if mg_ok:
        index_key = cache_key(mg, "global")
        index = {index_key: built}
        result = solve_row(args, mg, outdir, index, hashes)
        rows.append(result)
        print(json.dumps({"check": "mg_level2", "status": result.get("status"),
                          "residual": result.get("final_true_residual"),
                          "verify": result.get("verify_status"),
                          "wall_seconds": result.get("wall_seconds"),
                          "elapsed_seconds": result.get("elapsed_seconds"),
                          "source_read_mode": result.get("source_read_mode"),
                          "gauge_read_mode": result.get("gauge_read_mode"),
                          "source_read_seconds": result.get("source_read_seconds"),
                          "gauge_read_seconds": result.get("gauge_read_seconds")},
                         ensure_ascii=False))
    else:
        rows.append({
            "run_id": "validate-mg-cache",
            "phase": "validate",
            "solver": "cache_build",
            "status": built.get("status", "FAIL"),
            "notes": [built.get("notes", "cache build failed")],
        })
    csv_file = outdir / "validate.csv"
    for row in rows:
        write_row(outdir, row, csv_file)
    columns_ok = False
    try:
        with csv_file.open("r", newline="", encoding="utf-8") as handle:
            header = next(csv.reader(handle), [])
        columns_ok = all(name in header for name in CSV_COLUMNS)
    except OSError:
        columns_ok = False
    ok = mg_ok and all(row.get("status") == "PASS" for row in rows) and columns_ok
    print(json.dumps({"validate": "PASS" if ok else "FAIL",
                      "csv": str(csv_file), "columns": len(CSV_COLUMNS),
                      "columns_ok": columns_ok,
                      "new_columns": [name for name in CSV_COLUMNS
                                      if name in ("source_generate_seconds",
                                                  "source_read_seconds",
                                                  "gauge_generate_seconds",
                                                  "gauge_read_seconds",
                                                  "gauge_prewarm_seconds",
                                                  "source_prewarm_seconds",
                                                  "gauge_read_mode",
                                                  "source_read_mode")]},
                     ensure_ascii=False))
    return 0 if ok else 1


