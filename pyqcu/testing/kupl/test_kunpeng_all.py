def factorizations(value: int) -> Iterator[Tuple[int, int, int, int]]:
    for a in range(1, value + 1):
        if value % a:
            continue
        rest_a = value // a
        for b in range(1, rest_a + 1):
            if rest_a % b:
                continue
            rest_b = rest_a // b
            for c in range(1, rest_b + 1):
                if rest_b % c:
                    continue
                d = rest_b // c
                yield (a, b, c, d)


def choose_grid(lattice: Sequence[int], ranks: int, mode: str) -> Tuple[int, int, int, int]:
    if mode == "t-finest":
        return (1, 1, 1, ranks)
    candidates: List[Tuple[int, float, int, int, Tuple[int, int, int, int]]] = []
    for grid in factorizations(ranks):
        local = tuple(int(lattice[i]) // grid[i] for i in range(4))
        if any(value <= 0 or value % 2 for value in local):
            continue
        nonunit = sum(1 for value in grid if value > 1)
        spread = max(local) / min(local)
        imbalance = max(local) - min(local)
        candidates.append((-nonunit, spread, imbalance, -min(local), grid))
    if not candidates:
        raise ValueError(f"no even 4D grid for lattice={tuple(lattice)} ranks={ranks}")
    return min(candidates)[4]


def valid_rank_thread(ranks: int, threads: int, max_total: int) -> bool:
    return ranks > 0 and threads > 0 and ranks * threads <= max_total


