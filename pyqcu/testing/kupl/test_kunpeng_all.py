def index_existing_global_cache(outdir: Path, row: Dict[str, Any]) -> Optional[Dict[str, Any]]:
    wanted = {
        "lattice": list(row["lattice"]),
        "dtype": row["dtype"],
        "mass": row["mass"],
        "csw": row["csw"],
        "mg_grid": list(row["mg_grid"]),
        "nv_iters": row["nv_iters"],
        "seed": row["seed"],
    }
    candidates: List[Path] = []
    known = REPO / "data/kupl_scaling_20261114/cache_l24_parallel.h5"
    if tuple(row["lattice"]) == LATTICES["L24"] and row["dtype"] == "c64":
        candidates.append(known)
    for directory in DEFAULT_CACHE_DIRS:
        if not directory.is_dir():
            continue
        candidates.extend(sorted(directory.glob("cache_*.h5")))
        candidates.extend(sorted(directory.glob("mg*/cache_*.h5")))
    seen = set()
    for cache in candidates:
        if cache in seen or not cache.is_file():
            continue
        seen.add(cache)
        manifest = cache.with_suffix(".json")
        if not manifest.is_file():
            alt = cache.with_name(cache.stem + ".json")
            manifest = alt if alt.is_file() else manifest
        data = read_json(manifest, {}) or {}
        identity = data.get("identity") or {}
        if not identity:
            continue
        ok = True
        for key, value in wanted.items():
            actual = identity.get(key)
            if key in ("lattice", "mg_grid"):
                actual_list = list(actual) if actual is not None else None
                if actual_list != value:
                    ok = False
                    break
            elif key == "dtype":
                actual_text = str(actual)
                if actual_text not in (value, "complex64" if value == "c64" else "complex128"):
                    ok = False
                    break
            elif actual != value:
                ok = False
                break
        if ok:
            return {
                "path": str(cache), "manifest": str(manifest),
                "identity": identity,
                "build_mg_cache_seconds": data.get("setup_seconds"),
                "setup_method": data.get("setup_method"),
                "cache_sha256": data.get("file_sha256"),
                "cache_kind": "global",
            }
    return None


