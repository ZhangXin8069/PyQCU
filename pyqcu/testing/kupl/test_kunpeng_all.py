def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        while True:
            chunk = handle.read(8 * 1024 * 1024)
            if not chunk:
                break
            digest.update(chunk)
    return digest.hexdigest()


class HashCache:
    def __init__(self, path: Path):
        self.path = path
        self.data: Dict[str, str] = read_json(path, {}) or {}
        self.dirty = False

    def sha256(self, path: Optional[Path]) -> Optional[str]:
        if path is None or not path.is_file():
            return None
        stat = path.stat()
        key = f"{path.resolve()}:{stat.st_size}:{stat.st_mtime_ns}"
        if key not in self.data:
            self.data[key] = file_sha256(path)
            self.dirty = True
            self.flush()
        return self.data[key]

    def flush(self) -> None:
        if self.dirty:
            atomic_write_json(self.path, self.data)
            self.dirty = False


def node_frequency() -> Dict[str, Any]:
    base = Path("/sys/devices/system/cpu/cpu0/cpufreq")
    result: Dict[str, Any] = {"node": socket.gethostname(),
                              "freq_khz": None, "freq_max_khz": None,
                              "governor": None}
    for key, name in (("freq_khz", "scaling_cur_freq"),
                      ("freq_max_khz", "cpuinfo_max_freq"),
                      ("governor", "scaling_governor")):
        try:
            text = (base / name).read_text(encoding="utf-8").strip()
            result[key] = int(text) if key != "governor" else text
        except (OSError, ValueError):
            pass
    return result


