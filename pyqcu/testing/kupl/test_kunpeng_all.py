def csv_path(outdir: Path, name: str = "kupl_kunpeng_all.csv") -> Path:
    return outdir / name


def upgrade_csv_schema(path: Path) -> List[str]:
    """Make an existing CSV's header compatible with ``CSV_COLUMNS``.

    New columns are added to the driver over time (for example the input
    timing columns ``source_generate_seconds`` / ``source_read_mode``).  An
    append-only CSV written by an older driver keeps its old header, so blindly
    appending new rows would shift every value.  Rewrite the file with the new
    header plus any legacy-only column, preserving every existing value, and
    leave a one-shot backup next to it.
    """
    if not path.is_file() or path.stat().st_size == 0:
        return list(CSV_COLUMNS)
    with path.open("r", newline="", encoding="utf-8") as handle:
        reader = csv.reader(handle)
        header = next(reader, [])
        rows = [row for row in reader]
    if header == list(CSV_COLUMNS):
        return header
    extra = [name for name in header if name not in CSV_COLUMNS]
    target = list(CSV_COLUMNS) + extra
    backup = path.with_name(f"{path.name}.schema.bak")
    if not backup.exists():
        shutil.copy2(path, backup)
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    with tmp.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.writer(handle)
        writer.writerow(target)
        for row in rows:
            record = dict(zip(header, row))
            writer.writerow([record.get(name, "") for name in target])
    os.replace(tmp, path)
    eprint(f"[CSV] upgraded {path} from {len(header)} to {len(target)} columns "
           f"(backup {backup.name})")
    return target


def append_csv(path: Path, row: Dict[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    upgrade_csv_schema(path)
    with path.open("a+", newline="", encoding="utf-8") as handle:
        fcntl.flock(handle.fileno(), fcntl.LOCK_EX)
        handle.seek(0, os.SEEK_END)
        empty = handle.tell() == 0
        writer = csv.DictWriter(handle, fieldnames=CSV_COLUMNS,
                                extrasaction="ignore")
        if empty:
            writer.writeheader()
        writer.writerow({key: row.get(key) for key in CSV_COLUMNS})
        handle.flush()
        fcntl.flock(handle.fileno(), fcntl.LOCK_UN)


def write_row(outdir: Path, row: Dict[str, Any], csv_file: Path) -> None:
    path = outdir / "rows" / f"{row['run_id']}.json"
    atomic_write_json(path, row)
    append_csv(csv_file, row)


def merge_rows(outdir: Path, csv_file: Path) -> int:
    rows = []
    for path in sorted((outdir / "rows").glob("*.json")):
        data = read_json(path, None)
        if isinstance(data, dict):
            rows.append(data)
    rows.sort(key=lambda item: str(item.get("run_id")))
    columns = list(CSV_COLUMNS)
    # Keep any legacy-only column of an older CSV so a merge never drops data;
    # row keys outside CSV_COLUMNS stay in rows/*.json only.
    if csv_file.is_file():
        columns.extend(name for name in upgrade_csv_schema(csv_file)
                       if name not in columns)
    csv_file.parent.mkdir(parents=True, exist_ok=True)
    tmp = csv_file.with_name(f".{csv_file.name}.{os.getpid()}.tmp")
    with tmp.open("w", newline="", encoding="utf-8") as handle:
        writer = csv.DictWriter(handle, fieldnames=columns,
                                extrasaction="ignore")
        writer.writeheader()
        for row in rows:
            writer.writerow({key: row.get(key) for key in columns})
    os.replace(tmp, csv_file)
    print(json.dumps({"csv": str(csv_file), "rows": len(rows),
                      "columns": len(columns), "status": "PASS"},
                     ensure_ascii=False))
    return 0


