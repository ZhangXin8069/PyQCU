def generate_random_source(path: Path, lattice: Sequence[int], seed: int,
                           dtype: str) -> Optional[Path]:
    try:
        import numpy as np
        import h5py
    except Exception as exc:  # noqa: BLE001
        eprint(f"[SKIP] cannot generate random source: {exc}")
        return None
    np_dtype = np.dtype(np.complex64 if dtype == "c64" else np.complex128)
    rng = np.random.default_rng(int(seed))
    shape = (4, 3, *lattice)
    data = (rng.normal(size=shape) + 1j * rng.normal(size=shape)).astype(np_dtype)
    tmp = path.with_name(f".{path.name}.{os.getpid()}.tmp")
    with h5py.File(tmp, "w") as handle:
        handle.create_dataset("data", data=data)
        handle.attrs["format"] = "pyqcu.simple.v1"
        handle.attrs["layout"] = "[spin,color,x,y,z,t]"
        handle.attrs["generator"] = "numpy PCG64 normal float64, cast"
        handle.attrs["seed"] = int(seed)
    os.replace(tmp, path)
    return path


def resolve_gauge(outdir: Path, lattice: Sequence[int], kind: str, seed: int,
                  dtype: str, prewarm: bool = False) -> Dict[str, Any]:
    """Gauge counterpart of :func:`resolve_source`.

    Reuse order: readable production gauge (``real``) or readable file from
    ``outdir`` (``random``) -> generate into ``outdir``.
    """
    notes: List[str] = []
    if kind not in ("real", "random"):
        notes.append(f"unsupported gauge kind {kind!r}")
        return artifact_result("gauge", None, None, None, None, notes)
    candidates: List[Tuple[str, Path]] = []
    if kind == "real":
        production = real_gauge_path(lattice)
        if production is not None:
            candidates.append(("production", production))
    fallback = gauge_fallback_path(outdir, lattice, kind, seed, dtype)
    candidates.append(("outdir", fallback))
    path: Optional[Path] = None
    origin: Optional[str] = None
    for name, candidate in candidates:
        if not candidate.is_file():
            continue
        ok, reason = h5_readable(candidate)
        if not ok:
            notes.append(f"{name} gauge unreadable ({reason}): {candidate}")
            continue
        path, origin = candidate, name
        break
    generated_seconds: Optional[float] = None
    if path is None:
        fallback.parent.mkdir(parents=True, exist_ok=True)
        started = time.perf_counter()
        if kind == "random":
            path = generate_random_gauge(fallback, lattice, seed, dtype)
        else:
            path = write_identity_gauge(fallback, lattice, dtype)
        generated_seconds = time.perf_counter() - started
        origin = "generated"
        if path is None:
            notes.append("gauge generation failed")
            return artifact_result("gauge", None, None, generated_seconds, None, notes)
        ok, reason = h5_readable(path)
        if not ok:
            notes.append(f"generated gauge unreadable ({reason}): {path}")
    prewarm_result = prewarm_h5(path) if prewarm and path is not None else None
    if prewarm_result is not None and prewarm_result.get("status") != "PASS":
        notes.append(f"gauge prewarm failed: {prewarm_result.get('error')}")
    return artifact_result("gauge", path, origin, generated_seconds,
                           prewarm_result, notes)


