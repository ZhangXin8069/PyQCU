def run_command(command: Sequence[str], env: Dict[str, str], cwd: Path,
                out_path: Path, err_path: Path, hard_timeout: int,
                review_timeout: int) -> Dict[str, Any]:
    out_path.parent.mkdir(parents=True, exist_ok=True)
    err_path.parent.mkdir(parents=True, exist_ok=True)
    started = time.perf_counter()
    returncode: Optional[int] = None
    error: Optional[str] = None
    # Match the production x_case driver: use GNU timeout, no new session.
    timed_command = ["timeout", "-k", "5s", f"{int(hard_timeout)}s", *command]
    with out_path.open("wb") as out_handle, err_path.open("wb") as err_handle:
        try:
            process = subprocess.Popen(
                list(timed_command), cwd=str(cwd), env=env,
                stdout=out_handle, stderr=err_handle,
                stdin=subprocess.DEVNULL, close_fds=False)
            returncode = process.wait()
        except Exception as exc:  # noqa: BLE001
            error = f"{type(exc).__name__}: {exc}"
            returncode = None
    elapsed = time.perf_counter() - started
    return {
        "returncode": returncode,
        "elapsed_seconds": elapsed,
        "review": bool(elapsed >= review_timeout),
        "timeout": returncode in (124, 137),
        "error": error,
    }


