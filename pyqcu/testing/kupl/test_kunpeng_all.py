def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    if args.shard_count <= 0 or args.shard_index < 0 or args.shard_index >= args.shard_count:
        parser.error("require 0 <= --shard-index < --shard-count")
    if args.hard_timeout <= 0 or args.timeout <= 0:
        parser.error("timeouts must be positive")
    if args.mode == "list":
        return mode_list(args)
    if args.mode == "prepare":
        return mode_prepare(args)
    if args.mode == "prewarm":
        return mode_prewarm(args)
    if args.mode == "solve":
        return mode_solve(args)
    if args.mode == "merge":
        return mode_merge(args)
    if args.mode == "run":
        return mode_run(args)
    if args.mode == "validate":
        return mode_validate(args)
    parser.error(f"unknown mode {args.mode}")
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
