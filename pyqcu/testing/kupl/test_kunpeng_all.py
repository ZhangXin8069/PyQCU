"""KUPL-QCU Kunpeng all-configuration performance driver.

This file is a *driver*, not a pytest module.  It wraps the existing
``pyqcu/testing/simple/kupl_multigrid.py`` and
``pyqcu/testing/simple/mpi/build_full_mg_cache.py`` entry points; it does not
modify them.

Modes
-----
``list``      print the expanded matrix as JSONL
``prepare``   build/reuse gauge, source and Legacy-MG cache artifacts
``prewarm``   pre-generate and page-cache-warm the gauge/source inputs
``solve``     run a shard of the matrix and append CSV rows
``merge``     merge ``rows/*.json`` into one CSV
``run``       run one explicitly specified configuration
``validate``  small-lattice smoke test (2 ranks, ``8 8 8 16``)

Input timing
------------
Every solve row separates *input* cost from *solver* cost:

``source_generate_seconds`` / ``gauge_generate_seconds``
    wall time this process spent writing the artifact (``None`` when the file
    already existed and was reused).
``source_prewarm_seconds`` / ``gauge_prewarm_seconds``
    wall time of the explicit pre-solve ``h5py`` read (``None`` when no
    prewarm was requested).
``source_read_seconds`` / ``gauge_read_seconds``
    read time *inside* the solver process(es), copied from the driver report.
``source_read_mode`` / ``gauge_read_mode``
    one of ``cold`` / ``warm`` / ``pre-generated``:

    * ``cold``          - generated by this invocation, i.e. the solve is the
      first read of a file that did not exist before;
    * ``warm``          - file existed and was explicitly prewarmed by this
      invocation (page cache hot before ``mpirun``);
    * ``pre-generated`` - file existed and was reused as-is (produced by an
      earlier run/``--mode prewarm``; page-cache state not controlled).

``wall_seconds`` stays the solver-only measurement (the driver wraps a single
``applyCloverMultigridQcu`` call), while ``elapsed_seconds`` is the whole row
wall clock: artifact resolution + generate + prewarm + ``mpirun`` startup +
solver + report parsing.

The script is intentionally usable both on a login node (validation) and
inside a ``dsub`` allocation (production).  It launches ``mpirun`` itself, so
the enclosing invocation must be a single task; see ``submit_kunpeng_all.sh``.
"""

